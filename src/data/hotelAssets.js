export const getAssetsBySystem = (systemId) =>
  ASSETS.filter((a) => a.systemId === systemId);

export const getSystemById = (id) =>
  HOTEL_SYSTEMS.find((s) => s.id === id);

export const getAssetById = (id) =>
  ASSETS.find((a) => a.id === id);

export const getTotalReplacementValue = () =>
  ASSETS.reduce((sum, a) => sum + a.aiReplacementValue, 0);

export const getSystemStats = (systemId) => {
  const assets = getAssetsBySystem(systemId);
  return {
    count: assets.length,
    totalValue: assets.reduce((sum, a) => sum + a.aiReplacementValue, 0),
    totalContractCost: assets.reduce((sum, a) => sum + a.serviceContractAmount, 0),
  };
};

export const getWarrantyStatus = (warrantyDate) => {
  const today = new Date();
  const expiry = new Date(warrantyDate);
  const diffDays = Math.ceil((expiry - today) / (1000 * 60 * 60 * 24));
  if (diffDays < 0) return { status: 'expired', label: 'Expired', color: '#FF4757' };
  if (diffDays < 90) return { status: 'expiring', label: 'Expiring Soon', color: '#FFA502' };
  return { status: 'active', label: 'Active', color: '#2ED573' };
};

export const getConditionColor = (condition) => {
  switch (condition) {
    case 'Excellent': return '#2ED573';
    case 'Good': return '#1E90FF';
    case 'Fair': return '#FFA502';
    case 'Poor': return '#FF4757';
    default: return '#747D8C';
  }
};
